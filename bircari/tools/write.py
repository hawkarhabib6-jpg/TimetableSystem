def chapter_2(d):
    D.heading_chapter(d, '٥-٢', 'یاسای ساین', 'Law of Sine')

    D.concept(d,
        'یاسای ساین پەیوەندی نێوان درێژی لاکان و ساینی گۆشە بەرامبەرەکانیان '
        'لە هەر سێگۆشەیەکدا دەردەخات — نەک تەنها لە سێگۆشەی گۆشەوەستاودا. '
        'مانای ئەمە ئەوەیە کە لە سێگۆشەی گشتیشدا دەتوانین لا و گۆشەی '
        'نەزانراو بدۆزینەوە.')

    D.law(d, 'یاسای ساین', [
        r'\frac{a}{\sin A}=\frac{b}{\sin B}=\frac{c}{\sin C}',
    ], note='هەر لایەک بەسەر ساینی ئەو گۆشەیەدا کە بەرامبەریەتی. تەنها دوو '
            'کەرت لە یەک کاتدا بەکاردێن.')

    D.heading_section(d, 'کەی یاسای ساین بەکاردێت؟')
    D.bullets(d, [
        'پێوانەی دوو گۆشە و درێژی یەک لا درابێت، بەمەرجێک ئەو لایە نەکەوێتە '
        'نێوان هەردوو گۆشەکە.',
        'درێژی دوو لا و پێوانەی یەک گۆشە درابێت، بەمەرجێک ئەو گۆشەیە '
        'نەکەوێتە نێوان هەردوو لاکە.',
    ])

    D.example(d, '١',
        ('لە سێگۆشەی ', '$ABC$', 'دا ', r'$C=27^\circ$', '، ',
         r'$A=58^\circ$', ' و ', '$BC=15$', '. درێژی ', '$AB$',
         ' بدۆزەرەوە.'),
        figure=fig('image74.png'),
        steps=[
            ('یاساکە دادەنێین بۆ ئەو دوو کەرتەی کە نەزانراوەکەیان تێدایە.',
             r'\frac{AB}{\sin C}=\frac{BC}{\sin A}'),
            ('بەهاکان جێگیر دەکەین.',
             r'\frac{AB}{\sin 27^\circ}=\frac{15}{\sin 58^\circ}'),
            ('خاچەڕەو لێکدان دەکەین.',
             r'AB\,\sin 58^\circ=15\,\sin 27^\circ'),
            ('هەردوو لا بەسەر ساینی ٥٨ پلەدا دابەش دەکەین.',
             r'AB=\frac{15\,\sin 27^\circ}{\sin 58^\circ}=8{.}03'),
        ],
        answer=r'$AB=8{.}03$')

    D.example(d, '٢',
        ('لە سێگۆشەیەکدا ', '$8$', ' و ', '$6$', ' درێژی دوو لان و ',
         r'$B=63^\circ$', '. پێوانەی گۆشەی ', '$C$', ' بدۆزەرەوە.'),
        figure=fig('image76.png'),
        steps=[
            ('یاساکە دادەنێین و خاچەڕەو لێکدان دەکەین.',
             r'8\,\sin C=6\,\sin 63^\circ'),
            ('هەردوو لا بەسەر ٨دا دابەش دەکەین.',
             r'\sin C=\frac{6\,\sin 63^\circ}{8}'),
            (('بە کرداری پێچەوانە گۆشەکە دەردەهێنین، چونکە ',
              r'$\sin^{-1}$', ' و ', r'$\sin$', ' یەکتر لادەبەن.'),
             r'C=\sin^{-1}\left(\frac{6\,\sin 63^\circ}{8}\right)=41{.}9^\circ'),
        ],
        answer=r'$C\approx 42^\circ$')

    D.mistakes(d, [
        'بەکارهێنانی یاسای ساین کاتێک لاکە دەکەوێتە نێوان هەردوو گۆشەکە. لەو '
        'حاڵەتەدا یاسای کۆساین پێویستە.',
        ('لەبیرکردنی ', r'$\sin^{-1}$', ' لە کۆتاییدا کاتێک داوای گۆشە '
         'دەکرێت. بەهای ', r'$\sin C$', ' خۆی گۆشە نییە.'),
        'جووتکردنی لایەک لەگەڵ گۆشەیەکدا کە بەرامبەری نییە.',
    ])

    D.tips(d, [
        'پێش هەموو شتێک، لای بەرامبەر هەر گۆشەیەک دیاری بکە؛ یاساکە تەنها '
        'جووتی (لا، گۆشەی بەرامبەری) بەکاردێنێت.',
        'کاتێک هەردوو گۆشە زانراو بن، گۆشەی سێیەم بە ١٨٠ کەم کردنەوە '
        'دەردەکەوێت و ئیتر هەر کەرتێک بەکاردێت.',
    ])


