def chapter_5(d):
    D.heading_chapter(d, '٥-٥', 'هاوئەنجامە سێگۆشەییە بنەڕەتییەکان',
                      'Fundamental Trigonometric Identities')

    D.concept(d,
        'هاوئەنجامە بریتییە لە یەکسانییەک کە بۆ هەموو بەهاکانی گۆڕاوەکە '
        'ڕاست دەبێت. لە جیاتی دانانی ژمارە بۆ سەلماندنی، لایەکی یەکسانییەکە '
        'دەگۆڕین تاکو دەگاتە لاکەی تر. ئەمە کرداری سەلماندنە.')

    D.law(d, 'پێناسەکان لەسەر بازنەی یەکە', [
        r'\sin\theta=\frac{y}{r},\qquad \cos\theta=\frac{x}{r},'
        r'\qquad \tan\theta=\frac{y}{x}',
    ], note='لێرەدا r دووری خاڵەکەیە لە خاڵی بنەڕەتەوە. هەر سێ هاوئەنجامە '
            'بنەڕەتییەکە لەم پێناسانەوە دەردەچن.')

    D.law(d, 'هاوئەنجامە بنەڕەتییەکان', [
        r'\tan\theta=\frac{\sin\theta}{\cos\theta}',
        r'\sin^{2}\theta+\cos^{2}\theta=1',
        r'1+\frac{\cos^{2}\theta}{\sin^{2}\theta}=\frac{1}{\sin^{2}\theta}',
    ], note='لە یەکەمیانەوە: هەموو ڕێژەیەک دەکرێت بە ساین و کۆساین '
            'بنووسرێتەوە — ئەمە کلیلی زۆربەی سەلماندنەکانە.')

    D.example(d, '١',
        ('ئەم هاوئەنجامە بسەلمێنە: ',
         r'$\tan\theta=\frac{\sin\theta}{\cos\theta}$'),
        steps=[
            ('لای ڕاست دەگرین و پێناسەکان جێگیر دەکەین.',
             r'\frac{\sin\theta}{\cos\theta}='
             r'\frac{\frac{y}{r}}{\frac{x}{r}}'),
            ('دابەشکردنی کەرت بەسەر کەرتدا دەبێت بە لێکدان لە پێچەوانەکەی.',
             r'=\frac{y}{r}\times\frac{r}{x}=\frac{y}{x}'),
            ('ئەمە خۆی پێناسەی تانجێنتە.', r'=\tan\theta'),
        ],
        answer='لای ڕاست گەیشتە لای چەپ، کەواتە هاوئەنجامەکە ڕاستە.')

    D.example(d, '٢',
        ('ئەم دەربڕینە ساکار بکەوە: ',
         r'$\frac{1-\sin^{2}x}{\cos x}$'),
        steps=[
            (('لە هاوئەنجامەی ', r'$\sin^{2}x+\cos^{2}x=1$', ' دەردەچێت کە ',
              r'$1-\sin^{2}x=\cos^{2}x$', '.'),
             r'\frac{1-\sin^{2}x}{\cos x}=\frac{\cos^{2}x}{\cos x}'),
            ('کورت دەکەینەوە.', r'=\cos x'),
        ],
        answer=r'$\cos x$')

    D.example(d, '٣',
        ('ئەم دەربڕینە ساکار بکەوە: ',
         r'$\frac{\cos^{2}x-1}{\sin x}$'),
        steps=[
            ('ڕیزبەندی سەرەوە دەگۆڕین بۆ ئەوەی شێوەی هاوئەنجامەکە وەربگرێت.',
             r'\frac{\cos^{2}x-1}{\sin x}='
             r'\frac{-\left(1-\cos^{2}x\right)}{\sin x}'),
            ('جێگیرکردنی هاوئەنجامەکە.',
             r'=\frac{-\sin^{2}x}{\sin x}'),
            ('کورت دەکەینەوە.', r'=-\sin x'),
        ],
        answer=r'$-\sin x$')

    D.tips(d, [
        'هەر شتێک بگۆڕە بۆ ساین و کۆساین. زۆربەی سەلماندنەکان بەم یەک '
        'هەنگاوە ساکار دەبن.',
        ('ئەگەر لە ئەنجامدا پێویستە تەنها ', r'$\sin$', ' بمێنێتەوە، ئەوا '
         'هەموو ', r'$\cos^{2}$', 'ەکان بگۆڕە بە ', r'$1-\sin^{2}$', '.'),
        'لەسەر یەک لا کار بکە — ئەوەی ئاڵۆزترە — و بیگەیەنە بەوی تر. هەردوو '
        'لا پێکەوە مەگۆڕە.',
    ])

    D.mistakes(d, [
        'دانانی ژمارەیەک لە جیاتی سەلماندن. دانان تەنها پیشان دەدات کە بۆ '
        'ئەو ژمارەیە ڕاستە، نەک بۆ هەمووی.',
        ('تێکەڵکردنی ', r'$\sin^{2}x$', ' لەگەڵ ', r'$\sin x^{2}$',
         '. یەکەمیان ', r'$(\sin x)^{2}$', 'ە.'),
        'لادانی هەردوو لای یەکسانییەکە بە هەمان کردار، وەک ئەوەی '
        'هاوکێشەیەکی ئاسایی بێت. لە سەلماندندا تەنها یەک لا دەگۆڕدرێت.',
    ])


