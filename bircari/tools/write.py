def chapter_1(d):
    D.heading_chapter(d, '٥-١', 'ڕێژە سێگۆشەییەکان',
                      'Trigonometric Ratios')

    D.concept(d,
        'لە هەر سێگۆشەیەکی گۆشەوەستاودا، ڕێژەی نێوان درێژی دوو لا تەنها بە '
        'پێوانەی گۆشەکە دیاری دەکرێت و پەیوەندی بە قەبارەی سێگۆشەکەوە نییە. '
        'واتە هەر دوو سێگۆشەی گۆشەوەستاو کە گۆشە تیژەکانیان یەکسان بن، هەمان '
        'ڕێژەیان هەیە. ئەم ڕاستییە بناغەی هەموو ئەم بەشەیە.')

    D.heading_section(d, 'ناوی لاکان')
    D.para(d, 'بەرامبەر ئەو گۆشەیەی کە کاری لەسەر دەکەین، سێ لاکە بەم '
              'شێوەیە ناو دەبرێن:')
    D.bullets(d, [
        'ژێ — درێژترین لا و هەمیشە بەرامبەری گۆشە وەستاوەکەیە.',
        'بەرامبەر — ئەو لایەی ڕووبەڕووی گۆشەکەیە.',
        'تەنیشت — ئەو لایەی لەتەنیشت گۆشەکەیەتی و ژێ نییە.',
    ])
    D.callout(d, 'سەرنج', [
        'لای تەنیشت و لای بەرامبەر بە گۆڕینی گۆشەی کارکردن جێگۆڕکێ دەکەن، '
        'بەڵام ژێ جێگیرە و هەرگیز ناگۆڕێت.',
    ], D.HEX_KEY_WASH, D.KEY, D.HEX_KEY)

    D.law(d, 'پێناسەی هەر سێ ڕێژەکە', [
        r'\sin A=\frac{\mathrm{opp}}{\mathrm{hyp}}',
        r'\cos A=\frac{\mathrm{adj}}{\mathrm{hyp}}',
        r'\tan A=\frac{\mathrm{opp}}{\mathrm{adj}}',
    ], note='opp = بەرامبەر،  adj = تەنیشت،  hyp = ژێ. ئەم کورتکراوانە لە '
            'هاوکێشەکاندا بەکاردێن تاکو نیشانە بیرکارییەکە پاک بمێنێتەوە.')

    D.example(d, '١',
        ('هەر سێ ڕێژە سێگۆشەییەکەی گۆشەی ', '$C$',
         ' لە سێگۆشەی خوارەوەدا بدۆزەرەوە.'),
        figure=fig('image11.png'),
        steps=[
            (('لاکان ناو دەبەین بەرامبەر گۆشەی ', '$C$',
              ': بەرامبەر = ٣، تەنیشت = ٤، ژێ = ٥.'), None),
            ('پێناسەکان جێبەجێ دەکەین.',
             r'\sin C=\frac{3}{5}'),
            ('بە هەمان شێوە بۆ دوو ڕێژەکەی تر.',
             r'\cos C=\frac{4}{5}'),
            (None, r'\tan C=\frac{3}{4}'),
        ],
        answer=r'$\sin C=\frac{3}{5},\; \cos C=\frac{4}{5},\; '
               r'\tan C=\frac{3}{4}$')

    D.heading_section(d, 'دۆزینەوەی درێژی لایەکی نەزانراو')
    D.para(d, 'ئەگەر پێوانەی گۆشەیەکی تیژ و درێژی یەک لا زانراو بن، ئەوا '
              'درێژی هەر لایەکی تر دەدۆزرێتەوە. هەڵبژاردنی ڕێژەکە بەپێی '
              'ئەو دوو لایە دەبێت کە لە مەسەلەکەدا بەشدارن:')
    D.table(d, ['دوو لاکە', 'ڕێژەی پێویست'], [
        ('بەرامبەر و تەنیشت', r'$\tan$'),
        ('بەرامبەر و ژێ', r'$\sin$'),
        ('تەنیشت و ژێ', r'$\cos$'),
    ])

    D.example(d, '٢',
        ('لە سێگۆشەکەدا ', '$BC=8$', ' و ', r'$A=37^\circ$',
         '. درێژی ', '$AC$', ' و ', '$AB$', ' بدۆزەرەوە.'),
        figure=fig('image13.png'),
        steps=[
            (('بۆ ', '$AC$', ': بەرامبەر و تەنیشت بەشدارن، بۆیە ', r'$\tan$',
              '.'), r'\tan 37^\circ=\frac{8}{AC}'),
            ('نەزانراوەکە جیا دەکەینەوە.',
             r'AC=\frac{8}{\tan 37^\circ}=10{.}61'),
            (('بۆ ', '$AB$', ': بەرامبەر و ژێ بەشدارن، بۆیە ', r'$\sin$',
              '.'), r'\sin 37^\circ=\frac{8}{AB}'),
            ('بە هەمان هەنگاو.', r'AB=\frac{8}{\sin 37^\circ}=13{.}29'),
        ],
        answer=r'$AC=10{.}61,\qquad AB=13{.}29$')

    D.heading_section(d, 'دۆزینەوەی پێوانەی گۆشە')
    D.para(d, 'ئەگەر درێژی دوو لا زانراو بن، ئەوا ڕێژەکە هەژمار دەکەین و '
              'پاشان بە کردارە پێچەوانەکە گۆشەکە دەدۆزینەوە.')
    D.law(d, 'کردارە پێچەوانەکان', [
        r'A=\sin^{-1}\left(\frac{\mathrm{opp}}{\mathrm{hyp}}\right)',
        r'A=\cos^{-1}\left(\frac{\mathrm{adj}}{\mathrm{hyp}}\right)',
        r'A=\tan^{-1}\left(\frac{\mathrm{opp}}{\mathrm{adj}}\right)',
    ], note='لە حاسیبەدا ئەمانە بە SHIFT پاشان sin یان cos یان tan '
            'بەکاردێن.')

    D.law(d, 'یاسای فیساگۆرس', [
        r'(\mathrm{hyp})^{2}=(\mathrm{a})^{2}+(\mathrm{b})^{2}',
    ], note='کاتێک درێژی دوو لا زانراو بن و لای سێیەم داوا بکرێت، بێ '
            'پێویست بە هیچ ڕێژەیەک بەکاردێت.')

    D.example(d, '٣',
        ('لە سێگۆشەی گۆشەوەستاودا ', '$NK=4$', ' و ', '$KM=6$',
         '. پێوانەی گۆشەی ', '$M$', ' و درێژی ژێ بدۆزەرەوە.'),
        figure=fig('image21.png'),
        steps=[
            (('بەرامبەر گۆشەی ', '$M$', ' و تەنیشتی زانراون، بۆیە ',
              r'$\tan$', '.'), r'\tan M=\frac{4}{6}'),
            ('بە کرداری پێچەوانە گۆشەکە دەردەهێنین.',
             r'M=\tan^{-1}\left(\frac{4}{6}\right)=33{.}69^\circ'),
            ('بۆ ژێ، یاسای فیساگۆرس بەکاردێنین.',
             r'(\mathrm{hyp})^{2}=(4)^{2}+(6)^{2}=16+36=52'),
            ('ڕەگی دووەمی هەردوو لا دەگرین.',
             r'\mathrm{hyp}=\sqrt{52}=7{.}21'),
        ],
        answer=r'$M\approx 34^\circ,\qquad MN\approx 7{.}21$')

    D.callout(d, 'سەرنج', [
        'کۆی گۆشەکانی ناوەوەی هەر سێگۆشەیەک ١٨٠ پلەیە. لە سێگۆشەی '
        'گۆشەوەستاودا یەکێکیان ٩٠ پلەیە، بۆیە کۆی هەردوو گۆشە تیژەکە ٩٠ '
        'پلە دەکات — ئەگەر یەکێکیان بزانیت، ئەوی تر بە لێدەرکردن دەردەکەوێت.',
    ], D.HEX_KEY_WASH, D.KEY, D.HEX_KEY)

    D.mistakes(d, [
        'ژێ بە بەرامبەر تێکەڵ کردن. ژێ هەمیشە بەرامبەری گۆشە وەستاوەکەیە و '
        'بە گۆڕینی گۆشەی کارکردن ناگۆڕێت.',
        'دانانی حاسیبە لەسەر دۆخی بازنەیی (RAD) کاتێک گۆشەکە بە پلەیە. پێش '
        'هەر هەژمارکردنێک دڵنیابە لە دۆخی DEG.',
        ('کاتێک نەزانراوەکە لە بنی کەرتەکەدایە — وەک ', r'$\tan 37^\circ='
         r'\frac{8}{AC}$', ' — ڕاستەوخۆ لێکدانی ناکرێت؛ سەرەتا دەبێ بۆ '
         'سەرەوە بگوازرێتەوە.'),
        'بەکارهێنانی یاسای فیساگۆرس لە سێگۆشەیەکدا کە گۆشە وەستاوی نییە. '
        'ئەم یاسایە تەنها بۆ سێگۆشەی گۆشەوەستاوە.',
    ])

    D.tips(d, [
        'ناوی ڕێژەکان بە SOH · CAH · TOA لەبیر بمێنە.',
        'سەرەتا بپرسە: کام دوو لا لە مەسەلەکەدا بەشدارن؟ ئەو دوو لایە خۆیان '
        'دەڵێن کام ڕێژە بەکاربهێنیت.',
        'ئەگەر درێژی دوو لا زانراو بێت و لای سێیەم داوا بکرێت، فیساگۆرس '
        'خێراترە لە هەر ڕێژەیەک.',
    ])


