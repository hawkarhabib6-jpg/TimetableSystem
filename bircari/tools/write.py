def chapter_ref_angles(d):
    D.heading_chapter(d, '٥-١ ب', 'گۆشەی گەڕانەوە و گۆڕینی پێوانە',
                      'Reference Angles and Angle Measure')

    D.concept(d,
        'گۆشە لە باری پێوانەییدا ئەو گۆشەیەیە کە سەرەکەی لە خاڵی بنەڕەتدا '
        'بێت و لای یەکەمی بکەوێتە سەر نیوەی مووجەبی تەوەرەی ئاسۆییدا. ئەگەر '
        'سووڕانەوەکە پێچەوانەی میلی کاتژمێر بێت گۆشەکە مووجەبە، و بە '
        'ئاراستەی میلی کاتژمێر بێت سالبە.')

    D.heading_section(d, 'گۆشەی گەڕانەوە')
    D.para(d, 'گۆشەی گەڕانەوە ئەو گۆشە تیژەیە کە لە نێوان لای کۆتایی گۆشەکە '
              'و تەوەری ئاسۆییدا دروست دەبێت. هەمیشە مووجەبە و بەهای نێوان '
              'سفر و ٩٠ پلە وەردەگرێت، بۆیە بەهای ڕووت بەکاردێت.')

    D.table(d, ['چارەک', 'مەودا', 'گۆشەی گەڕانەوە'], [
        ('یەکەم', r'$0^\circ-90^\circ$', r'$\theta_{r}=\theta$'),
        ('دووەم و سێیەم', r'$90^\circ-270^\circ$',
         r'$\theta_{r}=\left|180^\circ-\theta\right|$'),
        ('چوارەم', r'$270^\circ-360^\circ$',
         r'$\theta_{r}=\left|360^\circ-\theta\right|$'),
    ])
    D.callout(d, 'سەرنج', [
        'کاتێک گۆشەکە سالب بێت، لە ناو یاساکەدا بە مووجەب دایبنێ. ئاراستەی '
        'سووڕانەوەکە چارەکەکە دەگۆڕێت، نەک بەهای گەڕانەوەکە.',
    ], D.HEX_KEY_WASH, D.KEY, D.HEX_KEY)

    D.example(d, '٤', ('گۆشەی گەڕانەوە بۆ هەریەک لەم گۆشانە بنووسە: ',
                       r'$125^\circ,\; 315^\circ,\; 97^\circ,\; 245^\circ$'),
        steps=[
            (('$125^\\circ$', ' لە چارەکی دووەمدایە.'),
             r'\theta_{r}=\left|180^\circ-125^\circ\right|=55^\circ'),
            (('$315^\\circ$', ' لە چارەکی چوارەمدایە.'),
             r'\theta_{r}=\left|360^\circ-315^\circ\right|=45^\circ'),
            (('$97^\\circ$', ' لە چارەکی دووەمدایە.'),
             r'\theta_{r}=\left|180^\circ-97^\circ\right|=83^\circ'),
            (('$245^\\circ$', ' لە چارەکی سێیەمدایە.'),
             r'\theta_{r}=\left|180^\circ-245^\circ\right|=65^\circ'),
        ])

    p = d.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    _f = fig('image25.png')
    if _f:
        try:
            p.add_run().add_picture(_f, width=Mm(110))
        except Exception:
            pass
    D.spacing(p, 3, 4)

    D.callout(d, 'نیشانەی ڕێژەکان لە چارەکەکاندا', [
        'چارەکی یەکەم — هەر سێ ڕێژەکە مووجەبن.',
        ('چارەکی دووەم — تەنها ', r'$\sin\theta$', ' مووجەبە.'),
        ('چارەکی سێیەم — تەنها ', r'$\tan\theta$', ' مووجەبە.'),
        ('چارەکی چوارەم — تەنها ', r'$\cos\theta$', ' مووجەبە.'),
    ], D.HEX_KEY_WASH, D.KEY, D.HEX_KEY)

    D.heading_section(d, 'گۆڕینی پێوانەی گۆشە')
    D.table(d, ['گۆڕین', 'لێکدان بە'], [
        ('لە پلەوە بۆ بازنەیی', r'$\theta\times\frac{\pi}{180}$'),
        ('لە بازنەییەوە بۆ پلە', r'$\theta\times\frac{180}{\pi}$'),
    ])
    D.tips(d, [
        ('ئەگەر ', '$\\pi$', ' لەگەڵ ژمارەکەدا نەبوو، لێکدانی ',
         r'$\frac{\pi}{180}$', ' بکە؛ ئەگەر لەگەڵیدا بوو، لێکدانی ',
         r'$\frac{180}{\pi}$', ' بکە.'),
    ])

    D.example(d, '٥', ('ئەمانەی خوارەوە بگۆڕە: ',
                       r'$45^\circ,\; \pi,\; 30^\circ,\; 2\pi$'),
        steps=[
            ('π لەگەڵیدا نییە، بۆیە لێکدانی π/180.',
             r'45^\circ\times\frac{\pi}{180}=\frac{\pi}{4}'),
            ('π لەگەڵیدایە، بۆیە لێکدانی 180/π.',
             r'\pi\times\frac{180}{\pi}=180^\circ'),
            ('بە هەمان ڕێسا.',
             r'30^\circ\times\frac{\pi}{180}=\frac{\pi}{6}'),
            (None, r'2\pi\times\frac{180}{\pi}=360^\circ'),
        ])

    D.mistakes(d, [
        ('لە یاسای چارەکی دووەم و سێیەمدا بەهای ڕووت لەبیرکردن. ',
         r'$\left|180^\circ-245^\circ\right|=65^\circ$',
         '، نەک ژمارەیەکی سالب.'),
        'گۆشەی سالب بە سالبی خۆی خستنە ناو یاساکە. سەرەتا چارەکەکەی دیاری '
        'بکە، پاشان بە مووجەب هەژماری بکە.',
        'لێکدان بە π/180 کاتێک گۆشەکە پێشتر بازنەیی بووە — ئەمە دوو جار '
        'گۆڕینە و ئەنجامەکە هەڵەیە.',
    ])


