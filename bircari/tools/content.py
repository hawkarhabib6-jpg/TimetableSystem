OPP, ADJ, HYP = 'بەرامبەر', 'تەنیشت', 'ژێ'


def ratio_box():
    """پێناسەی ڕێژەکان: کوردی لە دەرەوەی هاوکێشەکە دەمێنێتەوە."""
    sin_, cos_, tan_ = M(r'\sin A'), M(r'\cos A'), M(r'\tan A')
    rows = [
        (sin_, f'{OPP} ÷ {HYP}', 'ئەو لایەی بەرامبەر گۆشەکەیە، بەسەر ژێدا'),
        (cos_, f'{ADJ} ÷ {HYP}', 'ئەو لایەی تەنیشت گۆشەکەیە، بەسەر ژێدا'),
        (tan_, f'{OPP} ÷ {ADJ}',  'بەرامبەر بەسەر تەنیشتدا'),
    ]
    return table(['ڕێژە', 'پێناسە', 'مانا'],
                 [(f'<span class="c">{a}</span>', b, c) for a, b, c in rows])


